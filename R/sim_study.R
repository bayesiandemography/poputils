## 'sim_study' -----------------------------------------------------------------

#' Simulation Study of a Model
#'
#' Use simulated data to assess the performance of an estimation
#' model.
#'
#' `sim_study()` is a generic function. poputils does not supply any
#' methods: these come from modelling packages, such as bage and
#' popcounts, which re-export the generic. Each method documents its
#' own arguments and return value.
#'
#' @details
#' A simulation study generates data sets from a model, fits an
#' estimation model to each data set, and compares the estimates with
#' the values used to generate the data. By default, the data are
#' generated by the estimation model itself, which checks the
#' calibration and precision of its estimates. The data can also be
#' generated by a different model, which checks the estimation model's
#' robustness to misspecification.
#'
#' @param mod_est The estimation model: the model whose performance
#'   is being assessed.
#' @param ... Arguments passed to methods.
#'
#' @returns An object holding the results of the study, of a class
#'   defined by the method.
#'
#' @export
sim_study <- function(mod_est, ...) {
  UseMethod("sim_study")
}
